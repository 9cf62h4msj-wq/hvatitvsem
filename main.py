def duration_bucket(hours):
    if hours <= 2: return 2
    if hours <= 4: return 4
    if hours <= 6: return 6
    return 8

def get_min_for_dish(d):
    name = d.get("name", "").lower()
    sub = d.get("subcategory", "").lower()
    cat = d.get("category", "").lower()

    # Салаты
    if cat == "салаты":
        return 12

    # Горячее
    if cat == "горячее":
        if "соус" in sub or "добавки" in sub: return 10
        if "гарнир" in sub: return 10
        if "горячие закуски" in sub:
            if "креветки" in name or "гриль" in name: return 3
            if "шашлычок" in name: return 10
            if "мисо" in name or "язык" in name or "форель" in name or "рулет" in name or "грудка" in name: return 20
            if "крокеты" in name: return 20
            if "кесадилья" in name: return 10
            if "шампиньоны" in name: return 20
            return 10
        if "основное" in sub: return 10

    # Напитки
    if cat == "напитки":
        if "горячие" in sub or "кофе" in name or "чай" in name or "глинтвейн" in name:
            return 20
        return 15

    # Десерт
    if cat == "десерт":
        return 10

    if cat == "хлеб":
        return 10

    # Закуски
    if cat in ("холодные закуски", "закуски"):
        if "канапе" in sub: return 30
        if "бутерброд" in sub: return 30
        if "сэндвич" in sub: return 15
        if "брускетт" in sub: return 10
        if "рулетики" in sub: return 30
        if "рыба" in sub or "мясо" in sub or "сыр и овощи" in sub: return 30

        if "нарезки" in cat or "нарезки" in sub:
            if "сыр" in name: return 3
            if "орехи" in name: return 1
            if "маринад" in name: return 3
            if "буженина" in name: return 2
            if "охотничье" in name: return 3
            if "мясная" in name: return 3
            if "рыбная" in name: return 3
            if "овощная" in name and "шоте" in name: return 20
            if "овощная" in name: return 3
            if "фруктовая" in name: return 2
            return 3

        if "антипасто" in cat or "антипасто" in sub:
            return 3

    return 1

def calculate_random_with_budget(request: RandomCalculationRequest) -> dict:
    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()
    
    # Берем SC101 для всех банкетов
    base_scenario_id = "SC101" if request.scenario_id != "SC100" else "SC100"
    
    bucket = duration_bucket(request.hours)
    cursor.execute('SELECT category, dish_count, portion_norm, filterable FROM menu_structure WHERE scenario_id = ? AND duration_bucket = ?', (base_scenario_id, bucket))
    structure = cursor.fetchall()

    cursor.execute('SELECT category, name, unit, price_per_unit, package_size, tags, subcategory FROM dishes WHERE scenario_id = ?', (base_scenario_id,))
    all_dishes = cursor.fetchall()
    conn.close()

    by_cat = {}
    for row in all_dishes:
        cat = row[0]
        by_cat.setdefault(cat, []).append({
            "category": cat, "name": row[1], "unit": row[2],
            "price": row[3], "package_size": row[4], "tags": row[5] or "",
            "subcategory": row[6] or "",
        })

    # Seed для стабильности
    payload_str = f"{request.scenario_id}|{request.hours}|{request.adults}|{request.preferences}|{request.reroll}"
    seed = int(hashlib.md5(payload_str.encode()).hexdigest()[:8], 16)
    rng = random.Random(seed)

    effective_guests = request.adults
    items = []

    for (cat, dish_count, portion_norm, filterable) in structure:
        pool = by_cat.get(cat, [])
        if not pool: continue

        # Простой фильтр по предпочтениям
        if filterable and request.preferences and "auto" not in request.preferences:
            filtered = [d for d in pool if set(d["tags"].split(",")) & set(request.preferences)]
            if not filtered: filtered = pool # fallback
        else:
            filtered = pool

        # Выбор блюд
        chosen = rng.sample(filtered, min(dish_count, len(filtered)))
        chosen.sort(key=lambda d: -d["price"])

        n_positions = max(1, len(chosen))

        for d in chosen:
            # Считаем порции по норме
            if cat in ("Холодные закуски", "Напитки"):
                base_portions = (effective_guests * portion_norm) / n_positions
                calc_packages = max(1, int(math.ceil(base_portions / 5) * 5))
            elif cat == "Нарезки":
                calc_packages = max(1, math.ceil(effective_guests / 15))
            elif cat == "Антипасто":
                calc_packages = max(1, math.ceil(effective_guests / 20))
            elif cat == "Десерт":
                calc_packages = max(1, math.ceil((effective_guests * portion_norm) / n_positions))
            elif cat == "Хлеб":
                calc_packages = max(1, math.ceil(effective_guests / 7))
            else: # Салаты, Горячее
                calc_packages = max(1, math.ceil(effective_guests * portion_norm))

            # ПРИМЕНЯЕМ МИНИМУМ
            min_packages = get_min_for_dish(d)
            final_packages = max(calc_packages, min_packages)
            
            total_price = final_packages * d["price"]
            final_amount = final_packages * d["package_size"]

            items.append({
                "category": cat,
                "subcategory": d["subcategory"],
                "name": d["name"],
                "unit": d["unit"],
                "final_amount": round(final_amount, 2),
                "packages": final_packages,
                "package_size": d["package_size"],
                "total_price": round(total_price, 2),
                "cost_per_unit": d["price"],
                "off_filter": False,
            })

    total_cost = sum(i["total_price"] for i in items)
    
    result = {
        "items": items,
        "total_cost": round(total_cost, 2),
        "budget": request.budget,
        "is_within_budget": total_cost <= request.budget,
        "shortfall": round(max(0, total_cost - request.budget), 2),
        "remaining": round(max(0, request.budget - total_cost), 2),
        "price_per_guest": round(total_cost / max(1, effective_guests), 2),
        "adults": request.adults,
        "children": 0,
        "total_guests": request.adults,
        "scenario": "Банкет" if request.scenario_id != "SC100" else "Фуршет",
        "hours": request.hours,
        "recommended_budget": math.ceil(total_cost / 1000) * 1000 if total_cost > request.budget else None,
        "alcohol": False,
        "checks": [],
        "summary": {"total": 0, "errors": 0, "warnings": 0, "info": 0, "critical": 0}
    }
    return result

