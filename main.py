def init_db():
    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()
    cursor.execute('''CREATE TABLE IF NOT EXISTS scenarios (id TEXT PRIMARY KEY, name TEXT, format TEXT, duration INTEGER, audience TEXT, factor REAL)''')
    cursor.execute('''CREATE TABLE IF NOT EXISTS dishes (id INTEGER PRIMARY KEY AUTOINCREMENT, scenario_id TEXT, category TEXT, name TEXT, unit TEXT, price_per_unit REAL, adult REAL, child REAL, min REAL, max REAL, package_size REAL, tags TEXT, subcategory TEXT)''')
    cursor.execute('''CREATE TABLE IF NOT EXISTS menu_structure (scenario_id TEXT, category TEXT, duration_bucket INTEGER, dish_count INTEGER, portion_norm REAL, filterable INTEGER, PRIMARY KEY (scenario_id, category, duration_bucket))''')
    conn.commit()
    conn.close()

